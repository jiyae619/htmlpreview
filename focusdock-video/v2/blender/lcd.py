def lcd_image(line1, line2, backlight=1.0, W=1280, H=328):
    """Blue backlit 16x2 panel with visible pixel cells, like the real module."""
    cols, rows = 16, 2
    cw, ch = 6, 9                 # cell = 5x8 dots + gap
    mx, my = 4, 4                 # margin in dots
    nx, ny = cols * cw - 1 + 2 * mx, rows * ch - 1 + 2 * my
    p = min(W / nx, H / ny)
    img = Image.new('RGB', (W, H))
    d = ImageDraw.Draw(img)
    bl = backlight
    bg = (int(8 + 16 * bl), int(20 + 62 * bl), int(50 + 205 * bl))
    d.rectangle([0, 0, W, H], fill=bg)
    ox = (W - nx * p) / 2; oy = (H - ny * p) / 2
    rows_txt = [line1.upper().ljust(16)[:16], line2.upper().ljust(16)[:16]]
    off = tuple(min(255, int(c * 1.18 + 6)) for c in bg)
    on = (int(200 + 40 * bl), int(222 + 30 * bl), 255)
    for r in range(rows):
        for c in range(cols):
            g = FONT.get(rows_txt[r][c], FONT[' '])
            for gy in range(8):
                for gx in range(5):
                    lit = gy < 7 and g[gy][gx] == '1'
                    x = ox + (mx + c * cw + gx) * p; y = oy + (my + r * ch + gy) * p
                    d.rectangle([x + p * 0.08, y + p * 0.08, x + p * 0.92, y + p * 0.92], fill=on if lit else off)
    # soft backlight falloff + slight bloom of lit pixels
    glow = img.filter(ImageFilter.GaussianBlur(p * 0.6))
    return Image.blend(img, glow, 0.18)

def mmss(s):
    s = max(0, int(s)); return f'{(s // 60) % 100:02d}:{s % 60:02d}'

def phone_line(state, secs):
    """The real device's second line, e.g. 'PHONE AWAY00:00' / 'PHONE ON   00:03'."""
    return ('PHONE AWAY' + mmss(secs)) if state == 'away' else ('PHONE ON   ' + mmss(secs))
